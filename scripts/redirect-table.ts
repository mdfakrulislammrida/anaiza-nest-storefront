// Writes docs/redirect-map.md: every address in the old site's sitemap, run through the real public/.htaccess with the file list of
// the real build (out/), with the status it answers and whether the page it sends the visitor to exists in that build.
//   node --no-warnings scripts/redirect-table.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { OLD_SITE_URLS } from "../src/lib/oldSiteUrls.ts";
import { parseRules, resolve } from "../src/lib/rewriteRules.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "out");

function walk(directory: string, found: string[] = []): string[] {
  for (const name of readdirSync(directory)) {
    const path = join(directory, name);
    if (statSync(path).isDirectory()) walk(path, found);
    else found.push(relative(out, path).replaceAll("\\", "/"));
  }

  return found;
}

const files = new Set(walk(out));
const rules = parseRules(readFileSync(join(root, "public/.htaccess"), "utf8"));

const exists = (location: string): string => {
  const path = location.replace(/^\//, "").split("?")[0];

  return files.has(path === "" ? "index.html" : `${path}.html`) ? "yes" : "NO";
};

const rows = OLD_SITE_URLS.map((url) => {
  const outcome = resolve(rules, url, { files, https: true, host: "anaizanest.com" });
  const old = `\`${url}\``.replaceAll("|", "\\|");

  if (outcome.kind === "redirect") return `| ${old} | 301 | \`${outcome.location}\` | ${exists(outcome.location)} |`;
  if (outcome.kind === "file") return `| ${old} | 200 | served as it is (\`${outcome.path}\`) | yes |`;

  return `| ${old} | 200 | the home page | yes |`;
});

const doc = `# Old site addresses -> the new shop

Generated by \`node --no-warnings scripts/redirect-table.ts\` from \`public/.htaccess\` and the files of the latest build (\`out/\`), so the
table is what the rules do, not what they were meant to do. The same rules are tested in \`src/lib/oldSiteRedirects.test.ts\`
(a small interpreter of the rewrite rules: \`src/lib/rewriteRules.ts\`). The list of old addresses is the old site's sitemap
(\`src/lib/oldSiteUrls.ts\`).

All are permanent (301). The old query string is dropped (\`?sold=show\` and the like). The rules sit in section 3b of the file, after the
rules that serve a page that exists in the build, so \`/category/gifts\` is simply served, and before the client shells, which
would otherwise answer an old address with "not found".

## The table

| Old address | Status | Goes to | Target exists in the build |
| --- | --- | --- | --- |
${rows.join("\n")}

## How the targets were chosen

- **Products** (\`/product/<slug>-<3 digit id>\`, ids 194 to 207; a pipe, \`%7C\`, \`&\` and \`%E2%80%93\` in a slug are matched by the pattern, not
  by an exact spelling): a coffee cup and saucer set goes to the Morris coffee cup and saucer set, a tea coaster set to the tea coaster set; any
  other address whose words name a tea jar, a tea set, a cup or mug, or a gift goes to that category (tea jars, tea sets, cups and mugs, gifts),
  in that order; anything else goes to \`/shop\`. A product is never sent to the home page and never gets a 404. Earbuds, the phone stand, the
  clock-speaker, the speaker, the candle box, the bowl set and the wall decor have nothing like them in the new shop, so they go to \`/shop\`.
- **Categories**: \`/category/gifts\` exists in the new shop and is served as it is. The other nine old categories (car, music, mobile, electronic
  gadgets, watches, PC, laptop and computer, baby, lifestyle) and every \`/subcategory/*\` have no counterpart, so they go to \`/shop\`.
- **Pages**: \`order-procedure\` goes to \`/faq\` (its first answer is "How do I place an order?"; the shop has no separate how-to-order page),
  \`delivery-rules\` to \`/pages/shipping\`, \`return-policy\` to \`/pages/returns\`, \`terms-&-conditions\` to \`/pages/terms\`, \`privacy-policy\`
  to \`/pages/privacy\`, \`/site/contact-us\` to \`/contact\`, \`/page/test\` to the home page (it was a test page). Any other \`/page/*\` goes to \`/shop\`.
- **Customer area**: \`login\` to \`/account\`; \`register\` and \`forgot-password\` to \`/account?mode=register\` and \`/account?mode=forgot\` (this build
  teaches the account page to open on those two forms; \`/reset-password\` is only the page the emailed link opens, and needs the link's token);
  \`checkout\` to \`/checkout\`; \`order-track\` to \`/track-order\`. Any other \`/customer/*\` goes to \`/account\`.
- **/hot-deals** goes to \`/special-prices\` (rule 0, unchanged; its query string is kept).

## Things to know

- Targets that do not exist yet: none of the targets above is missing from the build (the last column). The new shop has no dedicated "how to order"
  page, which is why that one goes to the FAQ.
- A new product whose address ends in \`-\` and three digits would be redirected to a category or \`/shop\` if it is added after the last build (once
  it is in a build, its own page is served first). Unlikely, and a rebuild fixes it.
- The rules were run through a small interpreter of mod_rewrite written for this project, not through a real Apache or LiteSpeed. The patterns use only
  plain features (anchors, groups, alternation, \`{3}\`, file tests), and each rule can be tried on the host with \`curl -I https://anaizanest.com/<old address>\`
  after the upload; the table above is the answer to expect.
- The product redirects point at products by their current address (\`tea-coaster-set-of-6-with-holder\`, \`morris-ceramic-coffee-cup-and-saucer-set\`).
  If either is renamed in the admin, change the rule in \`public/.htaccess\` (and re-run the script).
`;

writeFileSync(join(root, "docs/redirect-map.md"), doc);
console.log(`docs/redirect-map.md written: ${rows.length} addresses, ${rows.filter((row) => row.includes("| NO |")).length} with a missing target.`);
